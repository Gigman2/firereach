#!/usr/bin/env node
/**
 * Generates api/seeds/safety_content.sql from the authored content file, and
 * refreshes each item's content_hash in place.
 *
 * Direction note: this is JSON -> SQL, the reverse of build-stations-bundle.mjs.
 * Station data is derived from an external authority so its seed is canonical;
 * safety content is authored and reviewed by a human working in prose, so the
 * readable artifact is canonical and the SQL is generated.
 *
 * Usage: npm run build:content-seed
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { contentHash } from "./contentHash.mjs";
import { validateContent } from "./contentValidate.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const contentPath = resolve(here, "../src/data/safety-content.bundled.json");
const outPath = resolve(here, "../../api/seeds/safety_content.sql");

const q = (value) =>
  value === null || value === undefined ? "NULL" : `'${String(value).replace(/'/g, "''")}'`;

const jsonb = (value) => `${q(JSON.stringify(value ?? []))}::jsonb`;

export function toSql(items) {
  const errors = validateContent(items);
  if (errors.length > 0) {
    throw new Error(`Refusing to generate SQL:\n  ${errors.join("\n  ")}`);
  }

  const header = [
    "-- Generated by app/scripts/build-safety-content-seed.mjs. Do not hand-edit.",
    "-- Source of truth: app/src/data/safety-content.bundled.json",
    "",
  ].join("\n");

  const rows = items.map((item) => {
    const r = item.review ?? {};
    return `INSERT INTO safety_content (
    slug, category, subcategory, title, summary, body,
    steps, tags, contextual_trigger, sources, content_hash,
    review_state, reviewer_name, reviewer_credential, last_reviewed, reviewed_content_hash
) VALUES (
    ${q(item.slug)},
    ${q(item.category)},
    ${q(item.subcategory)},
    ${q(item.title)},
    ${q(item.summary)},
    ${q(item.body)},
    ${jsonb(item.steps)},
    ${jsonb(item.tags)},
    ${q(item.contextual_trigger)},
    ${jsonb(item.sources)},
    ${q(item.content_hash)},
    ${q(r.state)},
    ${q(r.reviewer_name ?? null)},           -- reviewer_name
    ${q(r.reviewer_credential ?? null)},     -- reviewer_credential
    ${r.reviewed_at ? q(r.reviewed_at) + "::timestamptz" : "NULL"},
    ${q(r.content_hash ?? null)}
) ON CONFLICT (slug) DO UPDATE SET
    category = EXCLUDED.category,
    subcategory = EXCLUDED.subcategory,
    title = EXCLUDED.title,
    summary = EXCLUDED.summary,
    body = EXCLUDED.body,
    steps = EXCLUDED.steps,
    tags = EXCLUDED.tags,
    contextual_trigger = EXCLUDED.contextual_trigger,
    sources = EXCLUDED.sources,
    content_hash = EXCLUDED.content_hash,
    review_state = EXCLUDED.review_state,
    reviewer_name = EXCLUDED.reviewer_name,
    reviewer_credential = EXCLUDED.reviewer_credential,
    last_reviewed = EXCLUDED.last_reviewed,
    reviewed_content_hash = EXCLUDED.reviewed_content_hash;
`;
  });

  return `${header}${rows.join("\n")}`;
}

// Only run when invoked directly, so the test can import toSql cleanly.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const items = JSON.parse(readFileSync(contentPath, "utf8"));

  let rehashed = 0;
  for (const item of items) {
    const fresh = contentHash(item);
    if (item.content_hash !== fresh) {
      item.content_hash = fresh;
      rehashed += 1;
    }
  }

  const sql = toSql(items);

  writeFileSync(contentPath, `${JSON.stringify(items, null, 2)}\n`);
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, sql);

  const stale = items.filter(
    (i) => i.review?.state === "reviewed" && i.review.content_hash !== i.content_hash
  );

  console.log(`Wrote ${items.length} items to ${outPath}`);
  console.log(`Refreshed ${rehashed} content hash(es)`);
  if (stale.length > 0) {
    console.warn(
      `\n  ${stale.length} item(s) were edited after review and will now show ` +
        `"awaiting review":\n    ${stale.map((i) => i.slug).join("\n    ")}`
    );
  }
}
